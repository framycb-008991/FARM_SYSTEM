let currentLocale = localStorage.getItem('preferred_locale') || 'pt-MZ';

function setLocale(langCode) {
  if (!I18N_DICTIONARY[langCode]) return;
  currentLocale = langCode;
  localStorage.setItem('preferred_locale', langCode);
  document.documentElement.lang = langCode;

  // 1. Translate all static HTML data-i18n elements
  applyTranslations();

  // 2. Re-render all active dynamic modules so all table rows are 100% translated!
  if (typeof window.onLocaleChange === 'function') {
    window.onLocaleChange(langCode);
  }
}

function t(key, fallback = '') {
  if (!key) return '';
  return I18N_DICTIONARY[currentLocale]?.[key] || I18N_DICTIONARY['pt-MZ']?.[key] || fallback || key;
}

// Message interpolation for backend-supplied message_key + params
// (WEATHER_INTEGRATION_SPEC.md §10 — the API never returns pre-formatted
// text). Params whose value is itself an i18n key (fieldKey, sourceKey,
// cycleKey, levelKey...) are resolved through the dictionary too.
function tParams(key, params = {}) {
  let s = t(key);
  Object.entries(params || {}).forEach(([k, v]) => {
    const val = (typeof v === 'string' && /^[a-z_]+\.[a-z0-9_]+(\.[a-z0-9_]+)*$/i.test(v)) ? t(v) : v;
    s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), val);
  });
  return s;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translation = t(key);
    if (translation) {
      el.innerHTML = translation;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const translation = t(key);
    if (translation) {
      el.setAttribute('placeholder', translation);
    }
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const translation = t(key);
    if (translation) {
      el.setAttribute('title', translation);
    }
  });
}
